import { test, expect } from '@playwright/test';

test('live API baseline, recursive evolution, architecture and preview proof', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?offline=true');
  await expect(page.getByRole('heading', { name: 'One region. Four systems.' })).toBeVisible();
  await page.getByLabel('Transit scenario').selectOption('event_surge');
  await expect(page.locator('.station')).toHaveCount(21);
  await page.getByRole('checkbox', { name: 'Enable offline preview' }).check();
  await page.getByLabel('Mutation planner').selectOption('rule_based');
  const baselineResponse = page.waitForResponse(response => response.url().endsWith('/api/simulation/run') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run baseline' }).click();
  const baseline = await (await baselineResponse).json();
  expect(baseline.job_id).toBeTruthy();
  await expect(page.getByRole('button', { name: 'Evolve harness' })).toBeEnabled();
  await expect(page.locator('.map-overlay')).toContainText('Frame');
  await expect(page.locator('.table-row').filter({ hasText: 'Passenger delay' }).locator('b').nth(1)).not.toHaveText('—');
  const evolutionResponse = page.waitForResponse(response => response.url().endsWith('/api/harness/evolve') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Evolve harness' }).click();
  const evolution = await (await evolutionResponse).json();
  expect(evolution.job_id).toBeTruthy();
  await expect(page.getByRole('button', { name: 'Evolve harness' })).toBeEnabled();
  await expect(page.locator('.decision')).toHaveCount(2);
  await expect(page.locator('.execution-history li')).not.toHaveCount(0);
  await expect(page.locator('.planner-label')).toContainText('Rule-based');
  await expect(page.locator('.topology svg')).toContainText('REGIONAL COORDINATOR');
  await expect(page.locator('.persistence-panel')).toContainText('Preview records are held only in memory');
  const metricCells = page.locator('.table-row').filter({ hasText: 'Passenger delay' }).locator('b');
  for (const cell of await metricCells.all()) await expect(cell).not.toHaveText('—');
  await page.getByRole('button', { name: 'Pause playback' }).click();
  const slider = page.getByRole('slider', { name: 'Simulation time' });
  await slider.press('End');
  for (let index = 0; index < 17; index++) await slider.press('ArrowLeft');
  await expect(page.locator('.agent-intervention')).not.toHaveCount(0);
  await page.locator('.trace-observations summary').click();
  await expect(page.locator('.trace-observations pre')).toContainText('observe');
  await expect(page.locator('.trace-observations pre')).toContainText('muni_agent');
  await expect(page.locator('.trace-observations pre')).toContainText('bart_agent');
  await expect(page.locator('.trace-observations pre')).toContainText('caltrain_agent');
  await page.locator('.trace-observations summary').click();
  await expect(page.locator('.replay-context')).toContainText('evolving');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/bayflow.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false);
  await page.screenshot({ path: 'test-results/bayflow-mobile.png', fullPage: true });
});

// Explicit opt-in: writes one real fixed-baseline run to the configured organizer Atlas Sandbox.
test('official Atlas baseline persists and exposes executable agent traces', async ({ page }, testInfo) => {
  test.skip(testInfo.config.metadata.atlasTest !== true, 'Set BAYFLOW_TEST_ATLAS=1 or explicitly --grep "official Atlas" to run the organizer Atlas browser test.');
  await page.goto('/');
  await page.getByLabel('Transit scenario').selectOption('event_surge');
  await expect(page.locator('.db-pill')).toContainText('Atlas connected');
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/simulation/run') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run baseline' }).click();
  const {job_id} = await (await responsePromise).json();
  await expect(page.getByRole('button', { name: 'Evolve harness' })).toBeEnabled();
  const job = await (await page.request.get(`/api/jobs/${job_id}`)).json();
  expect(job.status).toBe('completed');
  expect(job.result.persistence).toBe('atlas');
  expect(job.result.traces.some((trace: any) => trace.agent === 'muni_agent')).toBe(true);
  expect(job.result.traces.some((trace: any) => trace.agent === 'bart_agent')).toBe(true);
  expect(job.result.traces.some((trace: any) => trace.agent === 'caltrain_agent')).toBe(true);
  const stored = await (await page.request.get(`/api/simulation/${job.result.run_id}`)).json();
  expect(stored.run_id).toBe(job.result.run_id);
  expect(stored.metrics).toEqual(job.result.metrics);
  await expect(page.locator('.replay-context')).toContainText('v1 · fixed policy');
  await page.getByRole('button', { name: 'Pause playback' }).click();
  const slider = page.getByRole('slider', { name: 'Simulation time' });
  await slider.press('End');
  for (let index = 0; index < 17; index++) await slider.press('ArrowLeft');
  await page.screenshot({ path: 'test-results/bayflow-atlas.png', fullPage: true });
});

